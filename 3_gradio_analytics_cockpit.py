def filter_profiles_by_predictions(risk_val, sentiment_val):
    """Filters profiles matching risk/sentiment inputs with forced uppercase mapping."""
    matched = []
    target_risk = str(risk_val).upper() if risk_val else ""
    target_sentiment = str(sentiment_val).upper() if sentiment_val else ""

    if os.path.exists(PAYLOADS_DIR):
        for filename in os.listdir(PAYLOADS_DIR):
            if filename.endswith("_xdm.json"):
                try:
                    with open(os.path.join(PAYLOADS_DIR, filename), "r") as f:
                        payload = json.load(f)
                    analytics = payload.get("_your_tenant", {}).get("churnAnalytics", {})
                    if str(analytics.get("churnRiskLevel")).upper() == target_risk and str(analytics.get("sentimentLabel")).upper() == target_sentiment:
                        matched.append(filename.replace("_xdm.json", ""))
                except Exception:
                    pass
    choices = matched[:5] if matched else ["No matching records found"]
    return gr.Dropdown(choices=choices, value=choices if matched else None)

def filter_profiles_by_quality(score_val):
    """Extracts target profile codes matching Gemma's uncoupled 1-5 compliance ranks."""
    matched = []
    if os.path.exists(SUMMARY_FILE_PATH):
        try:
            with open(SUMMARY_FILE_PATH, "r") as f:
                audit_data = json.load(f)
            for record in audit_data:
                if int(record.get("relevance_score", 0)) == int(score_val):
                    matched.append(record.get("customer_id"))
        except Exception:
            pass
    choices = matched if matched else ["No audited records found at this tier"]
    return gr.Dropdown(choices=choices, value=choices if matched else None)

def load_integrated_customer_records(customer_id):
    """Loads raw database records and final XDM streaming envelopes simultaneously."""
    if not customer_id or "No" in customer_id:
        return "Select a profile identifier.", {}
    try:
        # Invokes your active shared_orchestrator compiled in your notebook
        raw_story = shared_orchestrator.get_clean_customer_story(customer_id)
        raw_json_str = json.dumps(raw_story, indent=2)
    except Exception:
        raw_json_str = f"{{\n  \"status\": \"Visualizing source data inputs for record: {customer_id}\"\n}}"
    try:
        file_path = os.path.join(PAYLOADS_DIR, f"{customer_id}_xdm.json")
        with open(file_path, "r") as f:
            xdm_envelope = json.load(f)
    except Exception:
        xdm_envelope = {"error": "Target Adobe XDM schema payload envelope file is missing."}
    return raw_json_str, xdm_envelope

def load_governance_audit_card(customer_id):
    """Fetches the exact audit evaluation dictionary row row for the target customer."""
    if not customer_id or "No" in customer_id:
        return "Select an active audited profile from the left sample pool menu context panels.", {}

    try:
        with open(SUMMARY_FILE_PATH, "r") as f:
            audit_data = json.load(f)
        for record in audit_data:
            if record.get("customer_id") == customer_id:
                # Format a highly detailed markdown callout header panel to explain the score
                summary_md = f"""### 🛡️ Auditor Compliance Review Card: {customer_id}
- **Accuracy Verification Score:** `{record.get('accuracy_score')}/5`
- **Contextual Relevance Rating:** `{record.get('relevance_score')}/5`

#### 🎯 Judge Rationale Justification Statement:
> *"{record.get('judge_rationale')}"*
"""
                return summary_md, record
    except Exception as e:
        return f"❌ Error retrieving data governance summary tracking rows: {e}", {}
    return "⚠️ Customer record not audited in summary file.", {}

